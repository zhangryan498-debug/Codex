def block_for(agent_name: str) -> str:
    if agent_name.endswith("-lead"):
        key, plat = "lead", ("douyin" if agent_name.startswith("douyin") else "tiktok")
    else:
        role = agent_name.split("-", 1)[1]
        plat = "douyin" if agent_name.startswith("douyin") else "tiktok"
        key = role if role in BLOCKS else None
        if key is None:
            key = {"visual-designer": "visual-designer",
                   "video-director": "video-director",
                   "video-teardown": "video-teardown",
                   "competitor-analyst": "competitor-analyst",
                   "shop-ops": "shop-ops",
                   "campaign-ops": "campaign-ops",
                   "live-ops": "live-ops",
                   "ad-buyer": "ad-buyer",
                   "selection": "selection"}.get(role, "")
    dy, tk = BLOCKS.get(key, ("", ""))
    if plat == "tiktok":
        body = TIKTOK_DEFERRED.strip() + "\n" + tk
    else:
        body = dy
    head = (f"## 数据接入（管道可用，勿再假设数据靠人工投喂）\n\n"
            f"数据通道的唯一事实源：`docs/knowledge/data-channel.md`（含网络边界实测、"
            f"三层通道架构、端点→岗位映射、合规边界）。管道位于项目目录 `data-pipeline/`。\n\n")
    return head + body + "\n" + COMMON


def main():
    changed = []
    for name in sorted(os.listdir(AGENTS)):
        d = os.path.join(AGENTS, name)
        p = os.path.join(d, "agent.md")
        if not os.path.isfile(p):
            continue
        s = open(p, encoding="utf-8").read()
        if "## 数据接入" in s:
            # 整段替换
            start = s.index("## 数据接入")
            end = s.index("## 产出标准", start)
            s = s[:start] + block_for(name).rstrip() + "\n\n" + s[end:]
            open(p, "w", encoding="utf-8").write(s)
            changed.append(name)
            continue
        if "## 产出标准" not in s:
            print(f"  ⚠️ {name}: 找不到『## 产出标准』，跳过")
            continue
        s = s.replace("## 产出标准", block_for(name).rstrip() + "\n\n## 产出标准", 1)
        open(p, "w", encoding="utf-8").write(s)
        changed.append(name)
    print(f"✅ 已写入 {len(changed)} 个 Agent 的「数据接入」段")
    for c in changed:
        print("   ", c)


if __name__ == "__main__":
    main()
